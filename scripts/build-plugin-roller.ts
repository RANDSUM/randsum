#!/usr/bin/env bun

/**
 * Plugin Roller Bundle
 *
 * Usage: bun run plugin:roller          # write the bundle
 *        bun run check:plugin-roller    # fail if the committed bundle is stale
 *
 * The randsum plugin's `/roll` mod (plugins/randsum/hooks/register.ts) runs in
 * Claude Code's hooks sandbox, which can import only files inside the plugin:
 * no node_modules, no workspace packages. So `roll` from @randsum/roller is
 * bundled into one committed ESM file beside it, and this script is the only
 * thing that writes it. The check mode runs in the root `check` chain and in
 * CI, so a roller change that is not re-bundled fails instead of shipping a
 * plugin that rolls with an old engine.
 *
 * Exit codes: 0 — written, or fresh; 1 — stale or the build failed.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dir, '..')
const ENTRY = join(ROOT, 'packages/roller/src/roll/index.ts')
const OUT = join(ROOT, 'plugins/randsum/hooks/roller.generated.js')

const HEADER =
  '// Generated by scripts/build-plugin-roller.ts from @randsum/roller. Do not edit.\n' +
  '// Regenerate with `bun run plugin:roller`.\n'

const build = await Bun.build({
  entrypoints: [ENTRY],
  format: 'esm',
  target: 'browser',
  minify: true
})

const output = build.outputs[0]
if (!build.success || output === undefined) {
  console.error('Plugin roller bundle failed:')
  for (const log of build.logs) console.error(log)
  process.exit(1)
}

const bundle = `${HEADER}${await output.text()}`

if (process.argv.includes('--check')) {
  const committed = (() => {
    try {
      return readFileSync(OUT, 'utf8')
    } catch {
      return ''
    }
  })()
  if (committed !== bundle) {
    console.error(
      'plugins/randsum/hooks/roller.generated.js is stale. Run `bun run plugin:roller` and commit it.'
    )
    process.exit(1)
  }
  console.log('Plugin roller bundle is fresh.')
} else {
  writeFileSync(OUT, bundle)
  console.log(`Wrote ${OUT} (${bundle.length} bytes).`)
}
