import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { CONFORMANCE_FILE } from '../../packages/roller/spec/vectors'

const STABLE_KEY_ORDER = [
  'id',
  'notation',
  'category',
  'seedRolls',
  'rerollRolls',
  'explodeRolls',
  'compoundRolls',
  'penetrateRolls',
  'sequenceRolls',
  'expectedPool',
  'expectedTotal',
  'section',
  'conformanceLevel',
  'expectedError',
  'errorDescription',
  'note'
] as const

function stableVector(v: object): object {
  return Object.fromEntries(
    STABLE_KEY_ORDER.filter(k => k in v).map(k => [k, (v as Record<string, unknown>)[k]])
  )
}

const output = {
  $id: CONFORMANCE_FILE.$id,
  specVersion: CONFORMANCE_FILE.specVersion,
  generatedFrom: CONFORMANCE_FILE.generatedFrom,
  conformanceLevels: CONFORMANCE_FILE.conformanceLevels,
  vectors: CONFORMANCE_FILE.vectors.map(stableVector)
}

const outDir = new URL('./public/conformance/', import.meta.url)
const outName = `v${CONFORMANCE_FILE.specVersion}.json`
const outPath = new URL(outName, outDir)
const raw = JSON.stringify(output, null, 2) + '\n'

// Format the generated conformance file with Biome (the repo's sole formatter,
// reading the root biome.json) so it matches house style.
const proc = Bun.spawnSync(['bunx', '@biomejs/biome', 'format', `--stdin-file-path=${outName}`], {
  stdin: new TextEncoder().encode(raw),
  cwd: import.meta.dir
})

if (proc.exitCode !== 0) {
  console.error('Biome failed:', new TextDecoder().decode(proc.stderr))
  process.exit(1)
}

const formatted = new TextDecoder().decode(proc.stdout)

// `--check` is the CI and pre-push guard. It compares in memory rather than with
// `git diff`, which writes the file and depends on the git environment it runs
// under, and it owns the whole directory: a vector file the generator did not
// produce would otherwise be served unchecked.
if (process.argv.includes('--check')) {
  const stray = readdirSync(outDir).filter(name => name !== outName)
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : ''
  const problems = [
    ...(current === formatted ? [] : [`public/conformance/${outName} is stale`]),
    ...stray.map(name => `public/conformance/${name} is not generated by conformance-gen.ts`)
  ]
  if (problems.length > 0) {
    console.error(`${problems.join('\n')}\nRun: bun run --filter @randsum/site conformance:gen`)
    process.exit(1)
  }
  console.warn(`public/conformance/ matches packages/roller/spec/vectors.ts`)
} else {
  await Bun.write(outPath, formatted)
  console.warn(`Written: ${outPath.pathname}`)
}
